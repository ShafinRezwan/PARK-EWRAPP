type InvoiceSaveRow = Omit<InvoiceFormRow, "invoiceAttachment"> & {
hasAttachment?: boolean;
};
type UpdateEWRBody = {
jobNumber: string;
jobId: string;
ewrNumber: string;
recipient?: string;
address?: string;
date: string;
description?: string;
labour?: LabourFormRow[];
equipment?: EquipmentFormRow[];
materials?: MaterialFormRow[];
invoices?: InvoiceSaveRow[];
invoiceMarkups?: InvoiceMarkupRow[];
};
type Props = { params: Promise<{ id: string }> };
type ApiError = Error & { status?: number };
function fail(status: number, message: string): never {
const error: ApiError = new Error(message);
error.status = status;
throw error;
}
function decimal(value: unknown, field: string): number {
if (value === "" || value === null || value === undefined) return 0;
const n = Number(value);
if (!Number.isFinite(n) || n < 0) fail(400, `Invalid ${field}.`);
return n;
}
function money(value: number): string {
return (Math.round((value + Number.EPSILON) * 100) / 100).toFixed(2);
}
function validDate(value: string): boolean {
if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
const d = new Date(`${value}T00:00:00.000Z`);
return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === value;
}
function errorResponse(error: unknown, fallback: string) {
if (typeof error === "object" && error !== null && "code" in error && error.code === "23505") {
return NextResponse.json({ error: "EWR number or record already exists." }, { status: 409 });
}
const status = error instanceof Error && "status" in error && typeof error.status === "number"
? error.status : 500;
if (status === 500) console.error(fallback, error);
return NextResponse.json({ error: status === 500 ? fallback : (error as Error).message }, { status });
}
// Only delete files matching the paths generated by saveAttachment().
// Never accept absolute paths, traversal segments, or unexpected file locations.
const STORED_ATTACHMENT_PATH = /^ewr\/[0-9a-f-]{36}\/invoices\/[0-9a-f-]{36}\.(?:pdf|jpg|png|webp)$/i;

async function cleanupStoredFiles(pathnames: string[]) {
  let root: string;
  try {
    root = getUploadRoot();
  } catch (error) {
    console.error("Attachment cleanup skipped: upload directory is not configured:", error);
    return;
  }
  for (const pathname of new Set(pathnames)) {
    if (!STORED_ATTACHMENT_PATH.test(pathname)) {
      console.error("Skipping unexpected attachment pathname:", pathname);
      continue;
    }
    const absolutePath = path.resolve(root, ...pathname.split("/"));
    if (!absolutePath.startsWith(root + path.sep)) {
      console.error("Skipping attachment outside upload directory:", pathname);
      continue;
    }
    try {
      await deleteStoredFile(absolutePath);
    } catch (error) {
      // The database transaction has already committed. Log for manual cleanup.
      console.error("Local attachment cleanup failed:", pathname, error);
    }
  }
}

